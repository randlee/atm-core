class QaLogContractTests(unittest.TestCase):
    """The QA metrics log is a stable contract (paths, record fields and their order); config never changes it."""

    ROUND_ROW = ("'{completed_at:$completed_at, completed_local:$completed_local, duration:$duration, phase:$phase, sprint:$sprint,\n"
                 "    task:$task, pr_number:(($pr_number|tonumber?)//null), iteration:$iteration, verdict:$verdict, tested:$tested,\n"
                 "    fnd:$fnd, blk:$blk, imp:$imp, min:$min}')\nprintf '%s\\n' \"$ROW\" >> .sc/qa-log/phase-d.jsonl")
    STATS_ROW = ("  {snapshot_at: $completed_at, snapshot_local: $completed_local, phase: $ph, trigger_task: $task,\n"
                 "   tot: ($f | length),\n")

    def test_log_paths_and_fields_are_unchanged(self):
        for example in ("qa-template-vars.json", "qa-template-fix-round-vars.json"):
            with self.subTest(example=example):
                result = _render("qa-template.xml.j2", _example(example))
                self.assertEqual(result.returncode, 0, result.stderr)
                step = result.stdout[result.stdout.index('<step id="j">'):]
                self.assertIn("mkdir -p .sc/qa-log\n", step)
                self.assertNotIn("LOCKDIR", step)   # one printf append per row; no lock
                self.assertIn(self.ROUND_ROW, step)
                self.assertIn(self.STATS_ROW, step)
                self.assertIn("min: ([$f[] | select(.status==\"open\" and .metadata.severity==\"minor\")] | length)}')\nprintf '%s\\n' \"$STATS\" >> .sc/qa-log/phase-d-stats.jsonl", step)


if __name__ == "__main__":
    unittest.main()


def test_daemon_sanity_has_no_pin_gate_or_build_running_merge():
    values = _example("dev-sanity-template-vars.json")
    values["sanity_close_mode"] = "daemon"
    values.pop("commit", None)
    result = _render("dev-sanity-template.xml.j2", values)
    assert result.returncode == 0, result.stderr
    assert "assignment-gates.py" not in result.stdout
    assert "bd-validation" in result.stdout
    assert "not a planning pin or a close prerequisite" in result.stdout
    assert "do not invoke Cargo" in result.stdout
    assert "sanity-task-close.md.j2" in result.stdout


def test_hook_escalation_template_tracks_recovery_and_preserves_error_state():
    import xml.etree.ElementTree as ET
    values = _example("hook-close-escalation-vars.json")
    values["detail"] = "reader failed ]]> <state>&unknown"
    result = _render("hook-close-escalation.xml.j2", values)
    assert result.returncode == 0, result.stderr
    document = ET.fromstring(result.stdout)
    error, workflow = document.find("error"), document.find("workflow")
    assert error is not None and error.text and workflow is not None and workflow.text
    assert values["detail"] in error.text
    assert "Unknown; inspect current beads" in error.text
    assert "only after recovery is verified" in workflow.text


def test_hook_repair_template_uses_installed_runner_path():
    values = _example("sanity-bead-repair-vars.json")
    result = _render("sanity-bead-repair.xml.j2", values)
    assert result.returncode == 0, result.stderr
    assert "python3 " + values["repair_script"] in result.stdout
    for flag, field in (("--phase", "phase"), ("--team", "team"), ("--original-task", "original_task"), ("--lead", "phase_lead")):
        assert f"{flag} {values[field]}" in result.stdout
    assert "/.claude/skills/atm-bd-orchestration/scripts/" not in result.stdout


def test_shipped_dev_and_fix_assignments_carry_no_host_build_policy():
    # Repository build policy (cargo parallelism, host sharing) belongs in the consumer's policy_path, not in the
    # templates every installing repository receives.
    for template, example in (("dev-template.xml.j2", "dev-template-vars.json"),
                              ("fix-assignment.xml.j2", "fix-assignment-vars.json")):
        result = _render(template, _example(example))
        assert result.returncode == 0, result.stderr
        assert "CARGO_BUILD_JOBS" not in result.stdout, template
        assert "devs share this host" not in result.stdout, template
